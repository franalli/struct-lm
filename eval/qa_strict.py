"""Re-score stored closed-book answers with the strict checker (scorers.qa_strict), no GPU.

  .venv/bin/python eval/qa_strict.py   # -> results/qa_strict/{evals.json,evals.md,flips.jsonl,dpo_pairs.json}

evals: every run with a row in results/table.md, from its saved generations
  (results/runs/<run>/generations.jsonl, domain_qa, the `output` run_eval scored: the first line
  for base models, answer_line for chat ones). Per run: qa_acc as scored (qa_correct; checked
  against the table), qa_strict, and both by answer kind and by seen/unseen half. A run whose
  generations miss current items is scored on what it has and flagged partial.
flips: every distinct (item, answer) whose verdict differs, with the strict reason, for reading
  against the gold before the numbers are trusted (rule 8).
dpo_pairs: the closed-book pairs of the as-run Stage 4 set (data/dpo/{train,val}.jsonl, labelled by
  sft_judge.same_fact): chosen answers the strict rule rejects, rejected answers it accepts.
"""

import json
from collections import Counter
from pathlib import Path

from scorers import answer_line, qa_correct, qa_strict_reason

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "results/qa_strict"
TASKS = REPO / "eval/tasks/domain_qa.jsonl"
SEEN = REPO / "eval/tasks/sft_seen_chunks.txt"
TABLE = REPO / "results/table.md"


def read_jsonl(p: Path) -> list[dict]:
    return [json.loads(line) for line in p.open()]


def table_rows() -> dict[str, dict]:
    lines = [ln for ln in TABLE.read_text().splitlines() if ln.startswith("|")]
    head = [c.strip() for c in lines[0].strip("|").split("|")]
    rows = {}
    for ln in lines[2:]:
        cells = [c.strip() for c in ln.strip("|").split("|")]
        rows[cells[0]] = dict(zip(head, cells))
    return rows


def mean(xs) -> float | None:
    xs = list(xs)
    return round(sum(xs) / len(xs), 4) if xs else None


def evals() -> tuple[dict, list[dict]]:
    items = {r["id"]: r for r in read_jsonl(TASKS)}
    seen = set(SEEN.read_text().split())
    out, flips = {}, {}
    for run, row in table_rows().items():
        path = REPO / "results/runs" / run / "generations.jsonl"
        gens = (
            {g["id"]: g for g in read_jsonl(path) if g["task"] == "domain_qa"}
            if path.exists()
            else {}
        )
        scored = []
        for i, ref in items.items():
            if i not in gens:
                continue
            o = gens[i]["output"]
            kind = ref.get("answer_kind", "other")
            tol = ref.get("tolerance", 0.02)
            reason = qa_strict_reason(o, ref["answer"], kind, tol)
            lenient = qa_correct(o, ref["answer"], ref["answer_type"], tol)
            half = "seen" if ref["source_chunk"] in seen else "unseen"
            scored.append((i, kind, half, lenient, reason is None))
            if lenient != (reason is None):
                f = flips.setdefault((i, o), {"id": i, "gold": ref["answer"], "kind": kind,
                                              "answer": o, "lenient": lenient, "reason": reason,
                                              "runs": []})  # fmt: skip
                f["runs"].append(run)
        if not scored:
            continue
        d = {
            "n": len(scored),
            "partial": len(scored) < len(items),
            "qa_acc": mean(s[3] for s in scored),
            "qa_strict": mean(s[4] for s in scored),
            "table_qa_acc": row.get("qa_acc"),
            "lenient_only": sum(s[3] and not s[4] for s in scored),
            "strict_only": sum(s[4] and not s[3] for s in scored),
        }
        for idx in (1, 2):
            for v in sorted({s[idx] for s in scored}):
                sel = [s for s in scored if s[idx] == v]
                d[f"{v}_n"] = len(sel)
                d[f"{v}_acc"], d[f"{v}_strict"] = mean(s[3] for s in sel), mean(s[4] for s in sel)
        out[run] = d
    return out, sorted(flips.values(), key=lambda f: (f["reason"] or "", f["id"]))


def md(res: dict) -> str:
    cols = ["n", "qa_acc", "qa_strict", "lenient_only", "strict_only", "seen_acc", "seen_strict",
            "unseen_acc", "unseen_strict", "number_strict", "identifier_strict", "term_strict"]  # fmt: skip
    lines = [
        "# Closed-book eval (domain_qa) re-scored with the strict checker",
        "",
        (
            "Generated by `eval/qa_strict.py`. qa_acc = `scorers.qa_correct` (the table's column), "
            "qa_strict = `scorers.qa_strict`; lenient_only / strict_only = items only one rule "
            "passes. Partial runs (v1 generations) are marked *."
        ),
        "",
        "| run | " + " | ".join(cols) + " |",
        "|---" * (len(cols) + 1) + "|",
    ]
    for run, d in res.items():
        cells = [str(d.get(c, "")) for c in cols]
        lines.append(f"| {run}{'*' if d['partial'] else ''} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def dpo_pairs() -> dict:
    import sys

    sys.path.insert(0, str(REPO / "data/scripts"))
    from dpo_common import records

    pairs = [
        p
        for s in ("train", "val")
        for p in read_jsonl(REPO / "data/dpo" / f"{s}.jsonl")
        if p["format"] == "closed_book"
    ]
    recs = records({p["prompt_id"] for p in pairs})
    res: dict = {"pairs": len(pairs), "chosen_wrong": Counter(), "rejected_right": 0,
                 "inverted": 0, "examples": []}  # fmt: skip
    for p in pairs:
        rec = recs[p["prompt_id"]]
        kind = rec["kind"]
        c = qa_strict_reason(answer_line(p["chosen"][0]["content"]), rec["gold"], kind)
        r = qa_strict_reason(answer_line(p["rejected"][0]["content"]), rec["gold"], kind)
        if c is not None:
            res["chosen_wrong"][c] += 1
            res["examples"].append({"id": p["id"], "kind": kind, "gold": rec["gold"],
                                    "chosen": p["chosen"][0]["content"], "reason": c})  # fmt: skip
        res["rejected_right"] += r is None
        res["inverted"] += c is not None and r is None
    res["chosen_wrong_total"] = sum(res["chosen_wrong"].values())
    res["by_kind"] = dict(Counter(e["kind"] for e in res["examples"]))
    return res


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    res, flips = evals()
    for run, d in res.items():
        t = d["table_qa_acc"]
        if t and not d["partial"] and t != "—" and abs(float(t) - d["qa_acc"]) > 6e-4:
            raise SystemExit(f"{run}: recomputed qa_acc {d['qa_acc']} != table {t}")
    (OUT / "evals.json").write_text(json.dumps(res, indent=2) + "\n")
    (OUT / "evals.md").write_text(md(res))
    with (OUT / "flips.jsonl").open("w") as f:
        for x in flips:
            f.write(json.dumps(x, ensure_ascii=False) + "\n")
    dp = dpo_pairs()
    (OUT / "dpo_pairs.json").write_text(json.dumps(dp, indent=2, ensure_ascii=False) + "\n")
    print(md(res))
    print("flips:", len(flips), dict(Counter(f["reason"] or "strict_only" for f in flips)))
    print("dpo closed-book pairs:", dp["pairs"], "chosen wrong (strict):", dp["chosen_wrong_total"],
          dict(dp["chosen_wrong"]), "by kind", dp["by_kind"], "rejected right:", dp["rejected_right"],
          "inverted:", dp["inverted"])  # fmt: skip


if __name__ == "__main__":
    main()
